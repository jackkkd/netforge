#!/usr/bin/env python3
"""Convert the supplied eye/circuit reference to embedded, plain-ASCII logos.

Only regeneration requires Pillow: python3 -m pip install Pillow
Normal C compilation uses the already-generated art_data.h and needs no Python.
Usage: python3 tools/generate_logo.py [reference-image]
"""
from pathlib import Path
import json
import sys
from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
VARIANTS = (
    ("splash_large", 96, 48),
    ("splash_medium", 72, 36),
    ("splash_small", 48, 24),
    ("splash_tiny", 36, 18),
    ("header_large", 28, 14),
    ("header_medium", 20, 10),
    ("header_small", 14, 5),
)
PALETTE = " .:-=+*#%@"


def main():
    reference = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "assets/logo-reference.png"
    with Image.open(reference) as original:
        image = original.convert("RGBA")
        white = Image.new("RGBA", image.size, "white")
        white.alpha_composite(image)
        grayscale = white.convert("L")
    lines = ["/* Generated by tools/generate_logo.py; do not edit by hand. */",
             "#ifndef NETFORGE_ART_DATA_H", "#define NETFORGE_ART_DATA_H"]
    for name, width, height in VARIANTS:
        scaled = grayscale.resize((width, height), Image.Resampling.LANCZOS)
        pixels = list(scaled.tobytes())
        art = []
        for row in range(height):
            art.append("".join(PALETTE[round((255 - pixel) * (len(PALETTE) - 1) / 255)]
                               for pixel in pixels[row * width:(row + 1) * width]).rstrip())
        (ROOT / "assets" / (name.replace("_", "-") + ".txt")).write_text(
            "\n".join(art) + "\n", encoding="ascii")
        lines.append("static const char *const " + name + "_lines[] = {")
        lines.extend("    " + json.dumps(row) + "," for row in art)
        lines.append("};")
        lines.append(f"static const NfAsciiLogo {name} = {{ {name}_lines, {width}, {height} }};")
    lines.extend(["#endif", ""])
    (ROOT / "src/art_data.h").write_text("\n".join(lines), encoding="ascii")
    print("Generated seven ASCII logo sizes and src/art_data.h.")


if __name__ == "__main__":
    main()
